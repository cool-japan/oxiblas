//! Test support shared by every SME2 test: the hardware gate, the kernel and
//! decision counters, the force-off switch, and FPSR access.
//!
//! - **Hardware gate.** [`hardware_or_skip`] decides whether a test that
//!   executes SME2 code runs. Without SME2 (an Apple M3, QEMU with a 256-bit
//!   streaming vector length) it prints one `skip:` line and returns `false`.
//!   With `OXIBLAS_TEST_REQUIRE_SME2` set (the QEMU runner's `-r`; the
//!   repository script `tools/sme2_qemu.sh` sets it in its `--positive` pass) a
//!   missing SME2 is a failure instead, so a misconfigured emulator cannot turn
//!   the whole suite into skips. With `OXIBLAS_TEST_EXPECT_NO_SME2` set (the
//!   negative pass) SME2 being *present* is a failure. With
//!   `OXIBLAS_TEST_SME2_MARKERS` set, every call that returns writes one line
//!   straight to the standard error handle, `sme2-gate: ran <test>` or
//!   `sme2-gate: skipped <test>` (see `gate_marker`). libtest does not
//!   capture that handle, so the line shows even for a passing test, and a
//!   QEMU pass can prove that a gated test really ran (or declined) SME2.
//! - **Kernel entries** ([`kernel_entries`]): a process-wide counter that
//!   every kernel generated by `sme_kernels!` increments on entry, also on
//!   rayon worker threads. Tests run in parallel, so compare with `>`.
//! - **Decisions** ([`decisions`]): a per-thread counter for the dispatch
//!   decision (`try_gemm` / `try_gemv` call [`note_decision`] when they take
//!   the SME2 path). Per thread, so exact comparisons are reliable.
//! - **Force-off** ([`force_off`]): while the returned guard lives,
//!   `detect::enabled` reports `false` on this thread, so a test can compute
//!   the NEON result in the same process and compare.
//! - **FPSR** ([`fpsr_read`], [`fpsr_write`]): the cumulative floating-point
//!   exception flags of the calling thread.
//!
//! All three environment variables count as set when they hold anything other
//! than an empty string or `0`, like `OXIBLAS_DISABLE_SME2`. Without
//! `OXIBLAS_TEST_SME2_MARKERS` the gate writes no marker line.

use std::cell::Cell;
use std::sync::atomic::{AtomicU64, Ordering};

use super::detect;

/// Makes a missing SME2 a test failure instead of a skip.
pub(crate) const REQUIRE_ENV: &str = "OXIBLAS_TEST_REQUIRE_SME2";
/// Makes a present SME2 a test failure (the negative pass).
pub(crate) const EXPECT_NO_ENV: &str = "OXIBLAS_TEST_EXPECT_NO_SME2";
/// Makes [`hardware_or_skip`] write a marker line for each decision.
pub(crate) const MARKERS_ENV: &str = "OXIBLAS_TEST_SME2_MARKERS";

/// FPSR.IOC: invalid operation.
pub(crate) const FPSR_IOC: u64 = 1 << 0;
/// FPSR.DZC: division by zero.
pub(crate) const FPSR_DZC: u64 = 1 << 1;
/// FPSR.OFC: overflow.
pub(crate) const FPSR_OFC: u64 = 1 << 2;
/// FPSR.UFC: underflow.
pub(crate) const FPSR_UFC: u64 = 1 << 3;
/// FPSR.IXC: inexact.
pub(crate) const FPSR_IXC: u64 = 1 << 4;
/// FPSR.IDC: input denormal.
pub(crate) const FPSR_IDC: u64 = 1 << 7;
/// FPSR.QC: cumulative saturation.
pub(crate) const FPSR_QC: u64 = 1 << 27;
/// What every change of PSTATE.SM writes to FPSR (`ResetSVEState`): all of
/// the flags above. Measured under QEMU (S-1 probe).
pub(crate) const FPSR_AFTER_SM_CHANGE: u64 =
    FPSR_IOC | FPSR_DZC | FPSR_OFC | FPSR_UFC | FPSR_IXC | FPSR_IDC | FPSR_QC;

/// Kernel entries in this process.
static KERNEL_ENTRIES: AtomicU64 = AtomicU64::new(0);

thread_local! {
    /// SME2 dispatch decisions taken on this thread.
    static DECISIONS: Cell<u64> = const { Cell::new(0) };
    /// Whether SME2 is forced off on this thread.
    static FORCED_OFF: Cell<bool> = const { Cell::new(false) };
}

/// The SME2 features a test needs.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum Need {
    /// FEAT_SME2 with a 512-bit streaming vector length (f32 kernels).
    F32,
    /// Additionally FEAT_SME_F64F64 (f64 kernels).
    F64,
}

/// Whether an environment variable is set to something other than an empty
/// string or `0`.
fn env_flag(name: &str) -> bool {
    std::env::var_os(name).is_some_and(|value| !value.is_empty() && value != "0")
}

/// Whether this process has the SME2 hardware that `need` asks for,
/// regardless of [`force_off`] and of the build's SIMD caps.
pub(crate) fn hardware_present(need: Need) -> bool {
    detect::hw().is_some_and(|hw| need == Need::F32 || hw.f64)
}

/// The hardware gate: `true` when a test that executes SME2 code should run.
///
/// # Panics
///
/// Panics when `OXIBLAS_TEST_REQUIRE_SME2` is set and the hardware is missing,
/// and when `OXIBLAS_TEST_EXPECT_NO_SME2` is set and it is present.
///
/// With `OXIBLAS_TEST_SME2_MARKERS` set it writes `gate_marker`'s line to
/// the standard error handle before it returns (not when it panics).
#[track_caller]
pub(crate) fn hardware_or_skip(test: &str, need: Need) -> bool {
    let present = hardware_present(need);
    match gate(
        need,
        present,
        env_flag(REQUIRE_ENV),
        env_flag(EXPECT_NO_ENV),
    ) {
        Ok(true) => {
            write_gate_marker(test, true);
            true
        }
        Ok(false) => {
            write_gate_marker(test, false);
            println!("skip: {test}: no SME2 ({need:?}) on this host");
            false
        }
        Err(why) => panic!("{test}: {why}"),
    }
}

/// The marker line for one decision of [`hardware_or_skip`], newline included:
/// `sme2-gate: ran <test>` when the test runs its SME2 code, `sme2-gate:
/// skipped <test>` when it does not.
fn gate_marker(test: &str, ran: bool) -> String {
    let decision = if ran { "ran" } else { "skipped" };
    format!("sme2-gate: {decision} {test}\n")
}

/// Writes [`gate_marker`]'s line when `OXIBLAS_TEST_SME2_MARKERS` is set.
///
/// `print!` and `eprint!` output of a passing test is captured by libtest and
/// never shown; a write to the standard error handle itself is not captured.
/// The line goes out in one `write_all`, so that parallel tests do not
/// interleave inside it. A failed write is ignored: the marker is evidence for
/// the QEMU script, and its absence already fails that script's pass.
fn write_gate_marker(test: &str, ran: bool) {
    use std::io::Write;
    if env_flag(MARKERS_ENV) {
        let line = gate_marker(test, ran);
        let _ = std::io::stderr().lock().write_all(line.as_bytes());
    }
}

/// The decision of [`hardware_or_skip`] for given inputs: run, skip, or the
/// reason the run is misconfigured.
fn gate(need: Need, present: bool, require: bool, expect_no: bool) -> Result<bool, String> {
    match (present, require, expect_no) {
        (true, _, true) => Err(format!(
            "SME2 ({need:?}) is present but {EXPECT_NO_ENV} is set"
        )),
        (false, true, _) => Err(format!(
            "SME2 ({need:?}) is not available but {REQUIRE_ENV} is set"
        )),
        (present, _, _) => Ok(present),
    }
}

/// Counts one kernel entry. Called by every kernel that `sme_kernels!`
/// generates, in test builds only.
pub(crate) fn note_kernel_entry() {
    KERNEL_ENTRIES.fetch_add(1, Ordering::Relaxed);
}

/// Kernel entries in this process so far.
pub(crate) fn kernel_entries() -> u64 {
    KERNEL_ENTRIES.load(Ordering::Relaxed)
}

/// Counts one SME2 dispatch decision on this thread.
pub(crate) fn note_decision() {
    DECISIONS.with(|count| count.set(count.get() + 1));
}

/// SME2 dispatch decisions taken on this thread so far.
pub(crate) fn decisions() -> u64 {
    DECISIONS.with(Cell::get)
}

/// Whether SME2 is forced off on this thread (read by `detect::enabled`).
pub(crate) fn forced_off() -> bool {
    FORCED_OFF.with(Cell::get)
}

/// Keeps SME2 forced off on this thread until it is dropped; then the
/// previous state returns (guards nest).
#[derive(Debug)]
#[must_use = "SME2 is forced off only while the guard lives"]
pub(crate) struct ForceOff {
    /// The state to restore.
    previous: bool,
}

/// Forces SME2 off on the calling thread while the guard lives.
///
/// The switch is thread-local, so rayon workers never see it. A driver must
/// therefore take the SME2 decision once, on the calling thread (`try_gemm` /
/// `try_gemv` ask `detect::enabled` there), and pass it down to its workers;
/// it never re-queries `enabled` on a worker. Otherwise a force-off
/// comparison test could silently run SME2 on the workers.
pub(crate) fn force_off() -> ForceOff {
    let previous = FORCED_OFF.with(|flag| flag.replace(true));
    ForceOff { previous }
}

impl Drop for ForceOff {
    fn drop(&mut self) {
        FORCED_OFF.with(|flag| flag.set(self.previous));
    }
}

/// The FPSR read as a template, for the template lint.
macro_rules! fpsr_read_template {
    () => {
        "mrs {fpsr}, fpsr"
    };
}

/// The FPSR write as a template, for the template lint.
macro_rules! fpsr_write_template {
    () => {
        "msr fpsr, {fpsr}"
    };
}

/// The two FPSR templates, for the template lint.
pub(crate) const FPSR_TEMPLATES: [&str; 2] = [fpsr_read_template!(), fpsr_write_template!()];

/// The calling thread's FPSR.
pub(crate) fn fpsr_read() -> u64 {
    let fpsr: u64;
    // SAFETY: reading FPSR is always permitted at EL0 on AArch64 and touches
    // no memory, stack or condition flags.
    unsafe {
        core::arch::asm!(
            fpsr_read_template!(),
            fpsr = out(reg) fpsr,
            options(nomem, nostack, preserves_flags),
        );
    }
    fpsr
}

/// Sets the calling thread's FPSR.
pub(crate) fn fpsr_write(fpsr: u64) {
    // SAFETY: writing FPSR is always permitted at EL0 on AArch64. It changes
    // only the cumulative exception and saturation flags, which Rust code
    // never relies on; it touches no memory, stack or condition flags.
    unsafe {
        core::arch::asm!(
            fpsr_write_template!(),
            fpsr = in(reg) fpsr,
            options(nomem, nostack, preserves_flags),
        );
    }
}

/// The calling thread's SVCR and TPIDR2_EL0, or `None` without SME hardware
/// (the registers are then not readable).
pub(crate) fn sme_state() -> Option<(u64, u64)> {
    detect::hw()?;
    // SAFETY: `hw()` is `Some` only after the operating system reported SME
    // and the detection already executed this probe.
    let state = unsafe { detect::probe_thread_state() };
    Some((state.svcr, state.tpidr2))
}

#[test]
fn test_sme2_support_gate_decisions() {
    // Present hardware runs, unless the negative pass forbids it.
    assert_eq!(gate(Need::F32, true, false, false), Ok(true));
    assert_eq!(gate(Need::F64, true, true, false), Ok(true));
    // Missing hardware skips, unless the run requires it.
    assert_eq!(gate(Need::F32, false, false, false), Ok(false));
    assert_eq!(gate(Need::F64, false, false, true), Ok(false));
    let required = gate(Need::F32, false, true, false);
    assert!(required.is_err_and(|why| why.contains(REQUIRE_ENV)));
    let forbidden = gate(Need::F64, true, false, true);
    assert!(forbidden.is_err_and(|why| why.contains(EXPECT_NO_ENV)));
}

#[test]
fn test_sme2_support_gate_marker_text() {
    assert_eq!(
        gate_marker("test_sme2_smoke_f32_tile", true),
        "sme2-gate: ran test_sme2_smoke_f32_tile\n"
    );
    assert_eq!(
        gate_marker("test_sme2_kernel_f64_rows", false),
        "sme2-gate: skipped test_sme2_kernel_f64_rows\n"
    );
    // Exactly one line, ending in the test name.
    for ran in [true, false] {
        let line = gate_marker("t", ran);
        assert_eq!(line.matches('\n').count(), 1);
        assert!(line.ends_with(" t\n"));
    }
    assert_eq!(MARKERS_ENV, "OXIBLAS_TEST_SME2_MARKERS");
}

#[test]
fn test_sme2_support_environment_expectations() {
    // The QEMU passes: `-r` requires SME2, the negative pass forbids it.
    let require = env_flag(REQUIRE_ENV);
    let expect_no = env_flag(EXPECT_NO_ENV);
    assert!(
        !(require && expect_no),
        "{REQUIRE_ENV} and {EXPECT_NO_ENV} both set"
    );
    if require {
        assert!(hardware_present(Need::F32), "{REQUIRE_ENV}: no SME2");
        assert!(hardware_present(Need::F64), "{REQUIRE_ENV}: no SME_F64F64");
        assert!(detect::thread_ready());
    }
    if expect_no {
        assert!(
            !hardware_present(Need::F32),
            "{EXPECT_NO_ENV}: SME2 detected"
        );
        assert!(!detect::enabled::<f32>() && !detect::enabled::<f64>());
        assert!(!super::sme2_active());
    }
    println!(
        "{REQUIRE_ENV}: {require}, {EXPECT_NO_ENV}: {expect_no}, SME2 present: {}, SME_F64F64 present: {}",
        hardware_present(Need::F32),
        hardware_present(Need::F64)
    );
}

#[test]
fn test_sme2_support_counters() {
    let before = kernel_entries();
    note_kernel_entry();
    note_kernel_entry();
    assert!(kernel_entries() >= before + 2);

    let before = decisions();
    note_decision();
    assert_eq!(decisions(), before + 1);
    // Per thread: another thread starts from zero and does not move ours.
    let other = std::thread::spawn(|| {
        note_decision();
        decisions()
    })
    .join();
    assert!(matches!(other, Ok(1)), "{other:?}");
    assert_eq!(decisions(), before + 1);
}

#[test]
fn test_sme2_support_force_off_nests_and_is_per_thread() {
    assert!(!forced_off());
    {
        let _outer = force_off();
        assert!(forced_off());
        assert!(!detect::enabled::<f32>());
        assert!(!detect::enabled::<f64>());
        assert!(!super::sme2_active());
        {
            let _inner = force_off();
            assert!(forced_off());
        }
        // Dropping the inner guard keeps the outer one in force.
        assert!(forced_off());
        let elsewhere = std::thread::spawn(forced_off).join();
        assert!(matches!(elsewhere, Ok(false)), "{elsewhere:?}");
    }
    assert!(!forced_off());
}

#[test]
fn test_sme2_support_fpsr_round_trip() {
    let saved = fpsr_read();
    for flags in [0, FPSR_IXC, FPSR_DZC | FPSR_OFC, FPSR_AFTER_SM_CHANGE] {
        fpsr_write(flags);
        let read = fpsr_read();
        fpsr_write(saved);
        assert_eq!(read, flags, "FPSR wrote {flags:#x}, read {read:#x}");
    }
    assert_eq!(FPSR_AFTER_SM_CHANGE, 0x0800_009f);
    assert_eq!(FPSR_UFC, 0x8);
}

#[test]
fn test_sme2_support_sme_state_without_hw() {
    // Without SME hardware the state is never read (it would SIGILL).
    match sme_state() {
        None => assert!(detect::hw().is_none()),
        Some((svcr, tpidr2)) => {
            assert_eq!(svcr, 0, "SVCR outside any streaming region");
            assert_eq!(tpidr2, 0, "TPIDR2_EL0 outside any streaming region");
        }
    }
}
