#[test]
fn test_sme2_support_counters() {
    let before = kernel_entries();
    note_kernel_entry();
    note_kernel_entry();
    assert!(kernel_entries() >= before + 2);
    // The per-thread count moves by exactly the entries of this thread, and
    // another thread's entries move only the process-wide count.
    let here = kernel_entries_here();
    note_kernel_entry();
    assert_eq!(kernel_entries_here(), here + 1);
    let total = kernel_entries();
    let other = std::thread::spawn(|| {
        let start = kernel_entries_here();
        note_kernel_entry();
        note_kernel_entry();
        (start, kernel_entries_here())
    })
    .join();
    assert!(matches!(other, Ok((0, 2))), "{other:?}");
    assert_eq!(kernel_entries_here(), here + 1);
    assert!(kernel_entries() >= total + 2);

    let before = decisions();
    note_decision();
    assert_eq!(decisions(), before + 1);
    // Per thread: another thread starts from zero and does not move ours.
    let other = std::thread::spawn(|| {
        note_decision();
        decisions()
    })
    .join();
    assert!(matches!(other, Ok(1)), "{other:?}");
    assert_eq!(decisions(), before + 1);
}

#[test]
fn test_sme2_support_quiet_counters_nest_and_are_per_thread() {
    let (here, quiet) = (kernel_entries_here(), quiet_kernel_entries());
    {
        let _outer = quiet_counters();
        note_kernel_entry();
        {
            let _inner = quiet_counters();
            note_kernel_entry();
        }
        // Dropping the inner guard keeps the outer one in force.
        note_kernel_entry();
        // Another thread counts as usual.
        let other = std::thread::spawn(|| {
            note_kernel_entry();
            (kernel_entries_here(), quiet_kernel_entries())
        })
        .join();
        assert!(matches!(other, Ok((1, 0))), "{other:?}");
    }
    assert_eq!(kernel_entries_here(), here, "quiet entries were counted");
    assert_eq!(quiet_kernel_entries(), quiet + 3);
    // After the guard the entries count again.
    note_kernel_entry();
    assert_eq!(kernel_entries_here(), here + 1);
    assert_eq!(quiet_kernel_entries(), quiet + 3);
}

#[test]
fn test_sme2_support_force_off_nests_and_is_per_thread() {
    assert!(!forced_off());
    {
        let _outer = force_off();
        assert!(forced_off());
        assert!(!detect::enabled::<f32>());
        assert!(!detect::enabled::<f64>());
        assert!(!super::sme2_active());
        {
            let _inner = force_off();
            assert!(forced_off());
        }
        // Dropping the inner guard keeps the outer one in force.
        assert!(forced_off());
        let elsewhere = std::thread::spawn(forced_off).join();
        assert!(matches!(elsewhere, Ok(false)), "{elsewhere:?}");
    }
    assert!(!forced_off());
}

#[test]
fn test_sme2_support_fpsr_round_trip() {
    let saved = fpsr_read();
    for flags in [0, FPSR_IXC, FPSR_DZC | FPSR_OFC, FPSR_AFTER_SM_CHANGE] {
        fpsr_write(flags);
        let read = fpsr_read();
        fpsr_write(saved);
        assert_eq!(read, flags, "FPSR wrote {flags:#x}, read {read:#x}");
    }
    assert_eq!(FPSR_AFTER_SM_CHANGE, 0x0800_009f);
    assert_eq!(FPSR_UFC, 0x8);
}

