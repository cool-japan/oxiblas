    ///     for p in pairs of 0..kc                        label 6L: two depth steps per pass
    ///       A(i0.., p), B(p, j0..j0+8)  -> FMOPA into za0..za(L-1)
    ///       A(i0.., p+1), B(p+1, ..)    -> FMOPA into za0..za(L-1)
    ///     if kc is odd: the last depth step              label 7L
    ///     epilogue of the mode                           labels 50 (dispatch), 51..54
    ///       for each tile t whose first row i0 + 8t < m (rows predicated by p1)
    ///         for c in 0..ncols: slice c of za{t} -> C(i0 + 8t.., j0 + c)
    ///     next row panel / next column panel             label 59
    /// ```
    ///
    /// Only the live tiles of a row panel (those with at least one row below
    /// `m`) are zeroed, accumulated and stored. The depth steps are
    /// accumulated into each tile in ascending `p`, each FMOPA rounding once.
    /// A rows are loaded with zeroing predicates built from `m` (`p2` for one
    /// tile, the counters `pn9` for rows `i0..i0+31` and `pn10` for
    /// `i0+32..i0+63`), so no A element of a row `≥ m` is ever read; B rows are
    /// loaded all-true (the packed panel is zero-padded to 8 columns). The
    /// pointers move by `a_depth`, `a_panel` and `b_panel` exactly as given,
    /// so A may be read in place (`a_panel = 64`, `a_depth = lda`).
    ///
    /// # Epilogues
    ///
    /// For one slice (rows predicated by `p1`, C address in `x15`):
    ///
    /// - M0 (`mode` 0): `st1d {za{t}h.d[w12, 0]}, p1, [x15]`; C is not read.
    /// - M1 (`mode` 1): `mova z16.d, p1/m, za{t}h.d[w12, 0]`,
    ///   `ld1d {z17.d}, p1/z, [x15]`, `fadd z16.d, p1/m, z16.d, z17.d`
    ///   (`acc + C`), `st1d {z16.d}, p1, [x15]`.
    /// - M2 (`mode` 2): `mova`, `fmul z16.d, p1/m, z16.d, z28.d` (`acc *
    ///   alpha`), `st1d`; C is not read.
    /// - M3 (`mode` 3): `mova`, `fmul` by alpha, `ld1d` of C,
    ///   `fmla z16.d, p1/m, z17.d, z29.d` (`t + C * beta`, one rounding),
    ///   `st1d`. Multiplying by alpha and using FMLA unconditionally is exact
    ///   for `alpha == 1` and `beta == 1` (rule R3).
    ///
    /// FMOPA and the ZA slice stores raise no floating-point flags; the
    /// predicated SVE `fadd` / `fmul` / `fmla` raise the flags of their live
