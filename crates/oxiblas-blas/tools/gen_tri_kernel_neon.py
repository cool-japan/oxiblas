"""Generates crates/oxiblas-blas/src/level3/trsm/tri_kernel_neon.rs.

That file holds the NEON TRSM (forward substitution) and TRMM
(lower-triangular multiply) micro-panel kernels for f64 and f32, written out
in full (one statement per accumulator) because the lane-indexed intrinsics
need every lane index to be a constant. This script is development tooling
only: the build never runs it, and the generated file is committed.

Usage, from the workspace root:

    python3 -I crates/oxiblas-blas/tools/gen_tri_kernel_neon.py \\
        crates/oxiblas-blas/src/level3/trsm/tri_kernel_neon.rs 4 8 8 8

The arguments are the output file and the (MR, NR) register tiles of the f64
and of the f32 kernels. They must match F64_TILE / F32_TILE in tri_kernel.rs,
which a compile-time assertion there checks. The output is already in
rustfmt style, so `cargo fmt` leaves it unchanged.

To verify that the committed file is current, run the command above and then

    git diff --exit-code crates/oxiblas-blas/src/level3/trsm/tri_kernel_neon.rs

which must exit with status 0 (no differences).
"""
import sys

SCRIPT = "crates/oxiblas-blas/tools/gen_tri_kernel_neon.py"
OUTPUT = "crates/oxiblas-blas/src/level3/trsm/tri_kernel_neon.rs"

# rustfmt's default `max_width` (the workspace rustfmt.toml keeps it).
MAX_WIDTH = 100

GENERATED = '''// @generated by {script}. Do not edit by hand.
//
// Regenerate from the workspace root with
//
//     python3 -I {script} {output} {f64mr} {f64nr} {f32mr} {f32nr}
//
// (the tiles must match `F64_TILE` / `F32_TILE` in `tri_kernel.rs`), then check
// with `git diff --exit-code` that the committed file is current.

'''

HEADER = '''//! NEON micro-panels for `f64` ({f64mr} x {f64nr} tile) and `f32` ({f32mr} x {f32nr} tile):
//! forward substitution (TRSM) and lower-triangular multiply (TRMM).
//!
//! Same algorithms, packed layouts and operation order as the portable
//! `trsm_panel` / `trmm_panel` in [`super::tri_kernel`] (fused multiply-adds
//! throughout); the explicit lane-indexed instructions keep each column of
//! the diagonal tile in a few vector registers instead of one broadcast
//! register per entry, which removes the register spills of the
//! auto-vectorized tile code.
//!
//! The kernels are written out in full (one statement per accumulator) so
//! that every lane index is a constant, as the lane-indexed intrinsics need.

use core::arch::aarch64::{{
    float32x4_t, float64x2_t, vaddq_f32, vaddq_f64, vdupq_n_f32, vdupq_n_f64, vfmaq_laneq_f32,
    vfmaq_laneq_f64, vfmsq_laneq_f32, vfmsq_laneq_f64, vld1q_f32, vld1q_f64, vmulq_laneq_f32,
    vmulq_laneq_f64, vmulq_n_f32, vmulq_n_f64, vst1q_f32, vst1q_f64,
}};
'''


def vector_loads(ty, lanes, count):
    """Loads of `count` consecutive vectors from `base`."""
    return [
        f"vld1q_{ty}(base)" if j == 0 else f"vld1q_{ty}(base.add({j * lanes}))"
        for j in range(count)
    ]


def array_literal(items, indent):
    """Lines of an array expression at `indent` spaces, wrapped as rustfmt wraps it.

    rustfmt keeps the array on one line when it fits in MAX_WIDTH columns and
    otherwise puts one element per line with a trailing comma (the elements
    here are longer than its short-element threshold, so it never packs
    several per line).
    """
    pad = " " * indent
    one_line = pad + "[" + ", ".join(items) + "]"
    if len(one_line) <= MAX_WIDTH:
        return [one_line]
    return [pad + "["] + [f"{pad}    {item}," for item in items] + [pad + "]"]


def kernel(ty, mr, nr, kind):
    lanes = 2 if ty == "f64" else 4
    vt = "float64x2_t" if ty == "f64" else "float32x4_t"
    vr = nr // lanes          # vectors per accumulator row
    vl = mr // lanes          # vectors per L column
    assert nr % lanes == 0 and mr % lanes == 0
    acc = lambda r, v: f"a{r}_{v}"
    lines = []
    w = lines.append
    solve = kind == "trsm"
    name = f"{kind}_panel_{ty}"
    if solve:
        w(f"/// Forward substitution on one packed `{ty}` micro-panel (`MR = {mr}`, `NR = {nr}`).")
        w(f"pub(super) fn {name}<const UNIT: bool>(tri: &[{ty}], kb: usize, xp: &mut [{ty}]) {{")
    else:
        w(f"/// `X := alpha · L · X` on one packed `{ty}` micro-panel (`MR = {mr}`, `NR = {nr}`).")
        w(f"pub(super) fn {name}<const UNIT: bool>(")
        w(f"    tri: &[{ty}],")
        w("    kb: usize,")
        w(f"    xp: &mut [{ty}],")
        w(f"    alpha: Option<{ty}>,")
        w(") {")
    w(f"    const MR: usize = {mr};")
    w(f"    const NR: usize = {nr};")
    w("    let np = kb.div_ceil(MR);")
    w("    assert!(")
    w("        tri.len() >= MR * MR * np * (np + 1) / 2 && xp.len() >= np * MR * NR,")
    w('        "packed buffers too small"')
    w("    );")
    w("    let tp = tri.as_ptr();")
    w("    let xptr = xp.as_mut_ptr();")
    if solve:
        w("    for p in 0..np {")
    else:
        w("    // Bottom-up: tile p reads rows 0 .. (p + 1)·MR, none overwritten yet.")
        w("    for p in (0..np).rev() {")
    w("        let k = p * MR;")
    w("        let toff = MR * MR * p * (p + 1) / 2;")
    w("        // SAFETY: panel p reads `tri[toff .. toff + (k + MR)·MR]`, which ends at")
    w("        // MR²·(p+1)(p+2)/2 <= MR²·np(np+1)/2 <= tri.len() (asserted), and reads")
    w("        // and writes `xp[0 .. (k + MR)·NR]` with (k + MR)·NR <= np·MR·NR <=")
    w("        // xp.len() (asserted). Every access is a full-vector NEON load/store")
    w("        // (no alignment requirement) and `xp` is exclusively borrowed.")
    w("        unsafe {")
    w("            let cur = xptr.add(k * NR);")
    if solve:
        for r in range(mr):
            for v in range(vr):
                off = r * nr + v * lanes
                ptr = "cur" if off == 0 else f"cur.add({off})"
                w(f"            let mut {acc(r, v)} = vld1q_{ty}({ptr});")
    else:
        w(f"            let z = vdupq_n_{ty}(0.0);")
        for r in range(mr):
            for v in range(vr):
                w(f"            let mut {acc(r, v)} = z;")
    w("")
    w("            let mut l = tp.add(toff);")
    w("            let mut x = xptr.cast_const();")
    w("            for _ in 0..k {")
    for c in range(vl):
        ptr = "l" if c == 0 else f"l.add({c * lanes})"
        w(f"                let l{c} = vld1q_{ty}({ptr});")
    for v in range(vr):
        ptr = "x" if v == 0 else f"x.add({v * lanes})"
        w(f"                let x{v} = vld1q_{ty}({ptr});")
    op = "vfmsq" if solve else "vfmaq"
    for r in range(mr):
        for v in range(vr):
            w(f"                {acc(r, v)} = {op}_laneq_{ty}::<{r % lanes}>({acc(r, v)}, x{v}, l{r // lanes});")
    w("                l = l.add(MR);")
    w("                x = x.add(NR);")
    w("            }")
    w("")
    w("            // Diagonal tile: column c of L at t + c·MR.")
    w("            let t = tp.add(toff + k * MR);")
    w(f"            let col = |c: usize| -> [{vt}; {vl}] {{")
    w("                let base = t.add(c * MR);")
    for line in array_literal(vector_loads(ty, lanes, vl), 16):
        w(line)
    w("            };")
    if not solve:
        w(f"            let row = |c: usize| -> [{vt}; {vr}] {{")
        w("                let base = cur.add(c * NR);")
        for line in array_literal(vector_loads(ty, lanes, vr), 16):
            w(line)
        w("            };")
    for c in range(mr):
        w(f"            let cv = col({c});")
        if solve:
            # scale row c by inv diag, then subtract from rows below
            w("            if !UNIT {")
            for v in range(vr):
                w(f"                {acc(c, v)} = vmulq_laneq_{ty}::<{c % lanes}>({acc(c, v)}, cv[{c // lanes}]);")
            w("            }")
            for r in range(c + 1, mr):
                for v in range(vr):
                    w(f"            {acc(r, v)} = vfmsq_laneq_{ty}::<{r % lanes}>({acc(r, v)}, {acc(c, v)}, cv[{r // lanes}]);")
        else:
            w(f"            let xr = row({c});")
            w("            if UNIT {")
            for v in range(vr):
                w(f"                {acc(c, v)} = vaddq_{ty}({acc(c, v)}, xr[{v}]);")
            w("            } else {")
            for v in range(vr):
                w(f"                {acc(c, v)} = vfmaq_laneq_{ty}::<{c % lanes}>({acc(c, v)}, xr[{v}], cv[{c // lanes}]);")
            w("            }")
            for r in range(c + 1, mr):
                for v in range(vr):
                    w(f"            {acc(r, v)} = vfmaq_laneq_{ty}::<{r % lanes}>({acc(r, v)}, xr[{v}], cv[{r // lanes}]);")
    if not solve:
        w("")
        w("            if let Some(al) = alpha {")
        for r in range(mr):
            for v in range(vr):
                w(f"                {acc(r, v)} = vmulq_n_{ty}({acc(r, v)}, al);")
        w("            }")
    w("")
    for r in range(mr):
        for v in range(vr):
            off = r * nr + v * lanes
            ptr = "cur" if off == 0 else f"cur.add({off})"
            w(f"            vst1q_{ty}({ptr}, {acc(r, v)});")
    w("        }")
    w("    }")
    w("}")
    return "\n".join(lines) + "\n"


def main():
    if len(sys.argv) != 6:
        sys.exit(f"usage: python3 -I {SCRIPT} <out.rs> <f64 MR> <f64 NR> <f32 MR> <f32 NR>")
    out = sys.argv[1]
    f64mr, f64nr, f32mr, f32nr = map(int, sys.argv[2:6])
    tiles = dict(f64mr=f64mr, f64nr=f64nr, f32mr=f32mr, f32nr=f32nr)
    src = GENERATED.format(script=SCRIPT, output=OUTPUT, **tiles)
    src += HEADER.format(**tiles)
    src += f'''
/// `(MR, NR)` of the `f64` kernels below (checked against the packing layout
/// in [`super::tri_kernel`] at compile time).
pub(super) const F64_SHAPE: (usize, usize) = ({f64mr}, {f64nr});
/// `(MR, NR)` of the `f32` kernels below.
pub(super) const F32_SHAPE: (usize, usize) = ({f32mr}, {f32nr});
'''
    for kind in ("trsm", "trmm"):
        src += "\n" + kernel("f64", f64mr, f64nr, kind)
        src += "\n" + kernel("f32", f32mr, f32nr, kind)
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write(src)


main()
