//! Test support shared by every SME2 test: the hardware and backend gates,
//! the kernel and decision counters, the force-off switch, and FPSR access.
//!
//! - **Hardware gate.** [`hardware_or_skip`] decides whether a test that
//!   executes SME2 kernels directly runs. It asks the detection's candidate
//!   (`detect::candidate`: the operating system reports usable SME2), not
//!   the verdict of the first-use check, so that a kernel that is broken on
//!   this CPU still runs its own tests, which fail with their own messages
//!   instead of turning into skips. Without SME2 (an Apple M3, QEMU
//!   with a 256-bit streaming vector length) it prints one `skip:` line and
//!   returns `false`. With `OXIBLAS_TEST_REQUIRE_SME2` set (the QEMU runner's
//!   `-r`; the repository script `tools/sme2_qemu.sh` sets it in its
//!   `--positive` and `--hardware` passes) a missing SME2 is a failure instead,
//!   so neither a misconfigured emulator nor a machine without SME2 can turn
//!   the whole suite into skips. With
//!   `OXIBLAS_TEST_EXPECT_NO_SME2` set (the negative pass) SME2 being
//!   *present* is a failure. It looks at the hardware only: the build's SIMD
//!   caps do not stop a kernel that a test calls itself.
//! - **Backend gate.** [`backend_or_skip`] is the gate of every test that
//!   goes through the dispatch decision (`driver::try_gemm`,
//!   `gemv::sme2::try_gemv`). It decides as the hardware gate and
//!   additionally skips when the build caps SIMD below SME2
//!   (`force-scalar`, `max-simd-128` or `max-simd-256`, which make
//!   `SME2_ALLOWED` false and so turn the backend off however capable the
//!   hardware): `skip: <test>: this build caps SIMD below SME2`, and a
//!   failure instead when `OXIBLAS_TEST_REQUIRE_SME2` asks for SME2 anyway.
//!   It asks the verdict of the first-use check as `detect::enabled` does
//!   (through `detect::hw`, which runs the check on a ready thread): when
//!   the check failed it skips with the check's line, `skip: <test>: the
//!   SME2 first-use check failed: <line>`, also when
//!   `OXIBLAS_TEST_REQUIRE_SME2` is set (the failing kernel's own tests and
//!   the detection tests fail such a run, and the skip markers fail the
//!   positive pass of `tools/sme2_qemu.sh`).
//! - **Markers.** With `OXIBLAS_TEST_SME2_MARKERS` set, every gate call that
//!   returns writes one line straight to the standard error handle,
//!   `sme2-gate: ran <test>` or `sme2-gate: skipped <test>` (see
//!   `gate_marker`), and a test that proves the backend declines without
//!   SME2 writes `sme2-gate: declined <test>` ([`note_declined`]). libtest
//!   does not capture that handle, so the line shows even for a passing
//!   test, and a QEMU pass can prove that a gated test really ran (or
//!   skipped) SME2 and that the backend itself declined where it must.
//! - **Kernel entries**: every kernel generated by `sme_kernels!` counts its
//!   entry ([`note_kernel_entry`]) twice, except while the detection's
//!   first-use check runs on the thread ([`quiet_counters`]): the check can
//!   start inside any test, on any thread, and a test that compares a
//!   counter before and after a call must never see the check's own kernel
//!   calls. Those are counted apart ([`quiet_kernel_entries`]). [`kernel_entries_here`] counts the
//!   entries of the calling thread only, so exact comparisons are reliable
//!   while other tests run kernels: it is the proof that a kernel ran in
//!   every test, and the driver records its delta per part, on the thread
//!   that ran the part. [`kernel_entries`] is the process-wide count, rayon
//!   workers included; any test thread can raise it, so it proves nothing
//!   about one call, and only the counter's own test uses it.
//! - **Decisions** ([`decisions`]): a per-thread counter for the dispatch
//!   decision (`try_gemm` / `try_gemv` call [`note_decision`] when they take
//!   the SME2 path). Per thread, so exact comparisons are reliable.
//! - **Force-off** ([`force_off`]): while the returned guard lives,
//!   `detect::enabled` reports `false` on this thread, so a test can compute
//!   the NEON result in the same process and compare.
//! - **FPSR** ([`fpsr_read`], [`fpsr_write`]): the cumulative floating-point
//!   exception flags of the calling thread (the library's accessors of
//!   `fpstate.rs`, re-exported).
//!
//! All three environment variables count as set when they hold anything other
//! than an empty string or `0`, like `OXIBLAS_DISABLE_SME2`. Without
//! `OXIBLAS_TEST_SME2_MARKERS` the gate writes no marker line.

use std::cell::Cell;
use std::marker::PhantomData;
use std::sync::atomic::{AtomicU64, Ordering};

use super::SME2_ALLOWED;
use super::detect;

/// Makes a missing SME2 a test failure instead of a skip.
pub(crate) const REQUIRE_ENV: &str = "OXIBLAS_TEST_REQUIRE_SME2";
/// Makes a present SME2 a test failure (the negative pass).
pub(crate) const EXPECT_NO_ENV: &str = "OXIBLAS_TEST_EXPECT_NO_SME2";
/// Makes [`hardware_or_skip`] write a marker line for each decision.
pub(crate) const MARKERS_ENV: &str = "OXIBLAS_TEST_SME2_MARKERS";

/// FPSR.IOC: invalid operation.
pub(crate) const FPSR_IOC: u64 = 1 << 0;
/// FPSR.DZC: division by zero.
pub(crate) const FPSR_DZC: u64 = 1 << 1;
/// FPSR.OFC: overflow.
pub(crate) const FPSR_OFC: u64 = 1 << 2;
/// FPSR.UFC: underflow.
pub(crate) const FPSR_UFC: u64 = 1 << 3;
/// FPSR.IXC: inexact.
pub(crate) const FPSR_IXC: u64 = 1 << 4;
/// FPSR.IDC: input denormal.
pub(crate) const FPSR_IDC: u64 = 1 << 7;
/// FPSR.QC: cumulative saturation.
pub(crate) const FPSR_QC: u64 = 1 << 27;
/// What every change of PSTATE.SM writes to FPSR (`ResetSVEState`): all of
/// the flags above. Measured under QEMU.
pub(crate) const FPSR_AFTER_SM_CHANGE: u64 =
    FPSR_IOC | FPSR_DZC | FPSR_OFC | FPSR_UFC | FPSR_IXC | FPSR_IDC | FPSR_QC;

/// Kernel entries in this process.
static KERNEL_ENTRIES: AtomicU64 = AtomicU64::new(0);

thread_local! {
    /// Kernel entries on this thread.
    static KERNEL_ENTRIES_HERE: Cell<u64> = const { Cell::new(0) };
    /// Whether the counters are quiet on this thread ([`quiet_counters`]).
    static QUIET: Cell<bool> = const { Cell::new(false) };
    /// Kernel entries on this thread while the counters were quiet.
    static QUIET_ENTRIES: Cell<u64> = const { Cell::new(0) };
    /// SME2 dispatch decisions taken on this thread.
    static DECISIONS: Cell<u64> = const { Cell::new(0) };
    /// Whether SME2 is forced off on this thread.
    static FORCED_OFF: Cell<bool> = const { Cell::new(false) };
}

/// The SME2 features a test needs.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum Need {
    /// FEAT_SME2 with a 512-bit streaming vector length (f32 kernels).
    F32,
    /// Additionally FEAT_SME_F64F64 (f64 kernels).
    F64,
}

/// Whether an environment variable is set to something other than an empty
/// string or `0`.
fn env_flag(name: &str) -> bool {
    std::env::var_os(name).is_some_and(|value| !value.is_empty() && value != "0")
}

/// Whether this process has the SME2 hardware that `need` asks for, as the
/// detection's candidate reports it (the operating system reports usable
/// SME2; the first-use check is not consulted), regardless of
/// [`force_off`] and of the build's SIMD caps.
pub(crate) fn hardware_present(need: Need) -> bool {
    detect::candidate().is_some_and(|hw| need == Need::F32 || hw.f64)
}

/// Whether the SME2 backend is on for `need` in this process as far as the
/// hardware, the first-use check and the build go: `detect::hw` reports the
/// hardware (the first-use check passed; on a ready thread this call runs
/// it) and the build does not cap SIMD below SME2 (`SME2_ALLOWED`). That is
/// `detect::enabled` without [`force_off`].
pub(crate) fn backend_present(need: Need) -> bool {
    detect::hw().is_some_and(|hw| need == Need::F32 || hw.f64) && SME2_ALLOWED
}

/// The verdict of the first-use check as the backend gate sees it.
#[derive(Debug, Clone, PartialEq, Eq)]
enum Checked {
    /// The check passed.
    Passed,
    /// The check failed, with its line.
    Failed(String),
    /// The verdict is open: this thread is not ready, so it could not run
    /// the check.
    Open,
}

/// The verdict for the backend gate: `detect::hw` (which runs the check on
/// a ready thread while the verdict is open), then `detect::verdict`.
fn checked_verdict() -> Checked {
    let _ = detect::hw();
    match detect::verdict() {
        detect::Verdict::Passed => Checked::Passed,
        detect::Verdict::Failed(line) => Checked::Failed(line.to_owned()),
        detect::Verdict::Open => Checked::Open,
    }
}

/// The hardware gate: `true` when a test that executes SME2 kernels itself
/// should run.
///
/// It looks at the hardware only and ignores the build's SIMD caps
/// (`force-scalar`, `max-simd-128`, `max-simd-256`): a kernel that a test
/// calls directly runs regardless of them. A test that goes through the
/// dispatch decision (`driver::try_gemm`), which the caps turn off, uses
/// [`backend_or_skip`] instead.
///
/// # Panics
///
/// Panics when `OXIBLAS_TEST_REQUIRE_SME2` is set and the hardware is missing,
/// and when `OXIBLAS_TEST_EXPECT_NO_SME2` is set and it is present.
///
/// With `OXIBLAS_TEST_SME2_MARKERS` set it writes `gate_marker`'s line to
/// the standard error handle before it returns (not when it panics).
#[track_caller]
pub(crate) fn hardware_or_skip(test: &str, need: Need) -> bool {
    let verdict = gate(
        need,
        hardware_present(need),
        env_flag(REQUIRE_ENV),
        env_flag(EXPECT_NO_ENV),
    );
    finish_gate(
        test,
        need,
        verdict.map(|run| (!run).then_some(Skip::NoHardware)),
    )
}

/// The backend gate: `true` when a test that goes through the SME2 dispatch
/// decision should run, i.e. when the decision can take the SME2 path in
/// this build on this host.
///
/// As [`hardware_or_skip`], and in a build that caps SIMD below SME2 on
/// SME2 hardware it skips (`skip: <test>: this build caps SIMD below SME2`,
/// marker `sme2-gate: skipped <test>`), because the backend is off there and
/// a correct `try_gemm` declines. The declines of such a build are tested by
/// the ungated `declines_without_backend` tests.
///
/// # Panics
///
/// Panics when `OXIBLAS_TEST_EXPECT_NO_SME2` is set and the hardware is
/// present, when `OXIBLAS_TEST_REQUIRE_SME2` is set and the hardware is
/// missing, and when `OXIBLAS_TEST_REQUIRE_SME2` is set in a build that caps
/// SIMD below SME2.
#[track_caller]
pub(crate) fn backend_or_skip(test: &str, need: Need) -> bool {
    let present = hardware_present(need);
    // The verdict matters only where the backend could be on; asking for it
    // runs the first-use check on a ready thread.
    let checked = if present && SME2_ALLOWED {
        checked_verdict()
    } else {
        Checked::Passed
    };
    let verdict = backend_gate(
        need,
        present,
        SME2_ALLOWED,
        &checked,
        env_flag(REQUIRE_ENV),
        env_flag(EXPECT_NO_ENV),
    );
    finish_gate(test, need, verdict)
}

/// Why a gated test does not run its SME2 code.
#[derive(Debug, Clone, PartialEq, Eq)]
enum Skip {
    /// The hardware that the test needs is missing.
    NoHardware,
    /// The hardware is present, but the build caps SIMD below SME2.
    CappedBuild,
    /// The hardware is present, but the first-use check failed (its line).
    CheckFailed(String),
    /// The hardware is present, but the verdict is open (the calling thread
    /// is not ready).
    VerdictOpen,
}

/// Acts on a gate verdict: writes the one marker of the call and, for a
/// skip, the `skip:` line; panics with the reason of a misconfigured run.
#[track_caller]
fn finish_gate(test: &str, need: Need, verdict: Result<Option<Skip>, String>) -> bool {
    match verdict {
        Ok(None) => {
            write_gate_marker(test, Marker::Ran);
            true
        }
        Ok(Some(skip)) => {
            write_gate_marker(test, Marker::Skipped);
            match skip {
                Skip::NoHardware => println!("skip: {test}: no SME2 ({need:?}) on this host"),
                Skip::CappedBuild => println!("skip: {test}: this build caps SIMD below SME2"),
                Skip::CheckFailed(line) => {
                    println!("skip: {test}: the SME2 first-use check failed: {line}");
                }
                Skip::VerdictOpen => println!(
                    "skip: {test}: the SME2 first-use check has not run (this thread is not ready)"
                ),
            }
            false
        }
        Err(why) => panic!("{test}: {why}"),
    }
}

/// The kinds of marker line.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Marker {
    /// A gated test runs its SME2 code.
    Ran,
    /// A gated test skips its SME2 code.
    Skipped,
    /// A test saw the backend decline a call it would take with SME2.
    Declined,
}

/// The marker line of `kind` for `test`, newline included: `sme2-gate: ran
/// <test>`, `sme2-gate: skipped <test>` or `sme2-gate: declined <test>`.
fn gate_marker(test: &str, kind: Marker) -> String {
    let word = match kind {
        Marker::Ran => "ran",
        Marker::Skipped => "skipped",
        Marker::Declined => "declined",
    };
    format!("sme2-gate: {word} {test}\n")
}

/// Writes [`gate_marker`]'s line when `OXIBLAS_TEST_SME2_MARKERS` is set.
///
/// `print!` and `eprint!` output of a passing test is captured by libtest and
/// never shown; a write to the standard error handle itself is not captured.
/// The line goes out in one `write_all`, so that parallel tests do not
/// interleave inside it. A failed write is ignored: the marker is evidence for
/// the QEMU script, and its absence already fails that script's pass.
fn write_gate_marker(test: &str, kind: Marker) {
    use std::io::Write;
    if env_flag(MARKERS_ENV) {
        let line = gate_marker(test, kind);
        let _ = std::io::stderr().lock().write_all(line.as_bytes());
    }
}

/// Writes the marker `sme2-gate: declined <test>` (when
/// `OXIBLAS_TEST_SME2_MARKERS` is set): `test` called the dispatch decision
/// where the backend is off and saw it decline without touching anything.
/// The negative pass of `tools/sme2_qemu.sh` requires at least one such
/// line, the positive pass none.
pub(crate) fn note_declined(test: &str) {
    write_gate_marker(test, Marker::Declined);
}

/// The decision of [`hardware_or_skip`] for given inputs: run, skip, or the
/// reason the run is misconfigured. The backend gate with the caps and the
/// first-use check ignored.
fn gate(need: Need, present: bool, require: bool, expect_no: bool) -> Result<bool, String> {
    backend_gate(need, present, true, &Checked::Passed, require, expect_no)
        .map(|skip| skip.is_none())
}

/// The decision of [`backend_or_skip`] for given inputs (`present`: the
/// candidate has the hardware; `allowed` is `SME2_ALLOWED`; `checked` the
/// first-use verdict, looked at only when the hardware is present and the
/// build is not capped): `Ok(None)` to run, `Ok(Some(_))` to skip, or the
/// reason the run is misconfigured. A failed check skips even when
/// `OXIBLAS_TEST_REQUIRE_SME2` is set: the hardware is there, and the
/// failure is reported by the kernel's own tests and the detection tests.
fn backend_gate(
    need: Need,
    present: bool,
    allowed: bool,
    checked: &Checked,
    require: bool,
    expect_no: bool,
) -> Result<Option<Skip>, String> {
    match (present, allowed, require, expect_no) {
        (true, _, _, true) => Err(format!(
            "SME2 ({need:?}) is present but {EXPECT_NO_ENV} is set"
        )),
        (false, _, true, _) => Err(format!(
            "SME2 ({need:?}) is not available but {REQUIRE_ENV} is set"
        )),
        (true, false, true, _) => Err(format!(
            "this build caps SIMD below SME2 (force-scalar, max-simd-128 or max-simd-256) \
             but {REQUIRE_ENV} is set"
        )),
        (true, false, false, _) => Ok(Some(Skip::CappedBuild)),
        (false, _, false, _) => Ok(Some(Skip::NoHardware)),
        (true, true, _, false) => match checked {
            Checked::Passed => Ok(None),
            Checked::Failed(line) => Ok(Some(Skip::CheckFailed(line.clone()))),
            Checked::Open if require => Err(format!(
                "the SME2 first-use check has not run (this thread is not ready) but \
                 {REQUIRE_ENV} is set"
            )),
            Checked::Open => Ok(Some(Skip::VerdictOpen)),
        },
    }
}

/// Counts one kernel entry. Called by every kernel that `sme_kernels!`
/// generates, in test builds only. While the counters are quiet on this
/// thread ([`quiet_counters`]) it counts the entry in
/// [`quiet_kernel_entries`] only.
pub(crate) fn note_kernel_entry() {
    if QUIET.with(Cell::get) {
        QUIET_ENTRIES.with(|count| count.set(count.get() + 1));
        return;
    }
    KERNEL_ENTRIES.fetch_add(1, Ordering::Relaxed);
    KERNEL_ENTRIES_HERE.with(|count| count.set(count.get() + 1));
}

/// Kernel entries on the calling thread while its counters were quiet.
pub(crate) fn quiet_kernel_entries() -> u64 {
    QUIET_ENTRIES.with(Cell::get)
}

/// Keeps the kernel-entry counters of the calling thread quiet until it is
/// dropped (guards nest): [`note_kernel_entry`] then moves neither
/// [`kernel_entries_here`] nor [`kernel_entries`]. The detection's
/// first-use check holds one while it runs (`detect::run_checks`).
///
/// The guard is neither `Send` nor `Sync`: it restores the state of the
/// thread that drops it, so it must be dropped on the thread that created it.
#[derive(Debug)]
#[must_use = "the counters are quiet only while the guard lives"]
pub(crate) struct QuietCounters {
    /// The state to restore.
    previous: bool,
    /// Keeps the guard on its thread (`*const ()` is neither `Send` nor
    /// `Sync`).
    _not_send: PhantomData<*const ()>,
}

/// Makes the kernel-entry counters of the calling thread quiet while the
/// returned guard lives.
pub(crate) fn quiet_counters() -> QuietCounters {
    QuietCounters {
        previous: QUIET.with(|flag| flag.replace(true)),
        _not_send: PhantomData,
    }
}

impl Drop for QuietCounters {
    fn drop(&mut self) {
        QUIET.with(|flag| flag.set(self.previous));
    }
}

/// Kernel entries in this process so far.
pub(crate) fn kernel_entries() -> u64 {
    KERNEL_ENTRIES.load(Ordering::Relaxed)
}

/// Kernel entries on the calling thread so far. Per thread, so exact
/// comparisons are reliable even while other tests run kernels.
pub(crate) fn kernel_entries_here() -> u64 {
    KERNEL_ENTRIES_HERE.with(Cell::get)
}

/// Counts one SME2 dispatch decision on this thread.
pub(crate) fn note_decision() {
    DECISIONS.with(|count| count.set(count.get() + 1));
}

/// SME2 dispatch decisions taken on this thread so far.
pub(crate) fn decisions() -> u64 {
    DECISIONS.with(Cell::get)
}

/// Whether SME2 is forced off on this thread (read by `detect::enabled`).
pub(crate) fn forced_off() -> bool {
    FORCED_OFF.with(Cell::get)
}

/// Keeps SME2 forced off on this thread until it is dropped; then the
/// previous state returns (guards nest).
///
/// The guard is neither `Send` nor `Sync`: it restores the state of the
/// thread that drops it, so it must be dropped on the thread that created it.
#[derive(Debug)]
#[must_use = "SME2 is forced off only while the guard lives"]
pub(crate) struct ForceOff {
    /// The state to restore.
    previous: bool,
    /// Keeps the guard on its thread (`*const ()` is neither `Send` nor
    /// `Sync`).
    _not_send: PhantomData<*const ()>,
}

/// Forces SME2 off on the calling thread while the guard lives.
///
/// The switch is thread-local, so rayon workers never see it. A driver must
/// therefore take the SME2 decision once, on the calling thread (`try_gemm` /
/// `try_gemv` ask `detect::enabled` there), and pass it down to its workers;
/// it never re-queries `enabled` on a worker. Otherwise a force-off
/// comparison test could silently run SME2 on the workers.
pub(crate) fn force_off() -> ForceOff {
    let previous = FORCED_OFF.with(|flag| flag.replace(true));
    ForceOff {
        previous,
        _not_send: PhantomData,
    }
}

impl Drop for ForceOff {
    fn drop(&mut self) {
        FORCED_OFF.with(|flag| flag.set(self.previous));
    }
}

/// The calling thread's FPSR, and setting it: the library's accessors.
pub(crate) use super::fpstate::{fpcr_read, fpcr_write, fpsr_read, fpsr_write};

/// Whether the calling thread may enter a streaming region as far as its
/// SME state goes: the detection's candidate is present and the thread is
/// in the state of `ThreadState::ready` (SVCR = 0, TPIDR2_EL0 = 0, a 64-byte
/// streaming vector length), read through the raw register probe.
///
/// The precondition of a test that calls a kernel directly. Unlike
/// `detect::thread_ready`, it does not ask the verdict of the first-use
/// check (a kernel that is broken on this CPU must fail its own tests with
/// their own messages, not their precondition), never starts that check,
/// and does not consume the test seams of `detect::thread_ready` (the
/// pretend flag and the readiness countdown).
pub(crate) fn kernel_ready() -> bool {
    if detect::candidate().is_none() {
        return false;
    }
    // SAFETY: the candidate is present only after the operating system
    // reported SME and the detection already executed this probe.
    unsafe { detect::probe_thread_state() }.ready()
}

/// The calling thread's SVCR and TPIDR2_EL0, or `None` without an SME2
/// candidate (`detect::candidate`; the registers are then not readable).
/// It never starts the first-use check.
pub(crate) fn sme_state() -> Option<(u64, u64)> {
    detect::candidate()?;
    // SAFETY: the candidate is present only after the operating system
    // reported SME and the detection already executed this probe.
    let state = unsafe { detect::probe_thread_state() };
    Some((state.svcr, state.tpidr2))
}

#[test]
fn test_sme2_support_gate_decisions() {
    // Present hardware runs, unless the negative pass forbids it.
    assert_eq!(gate(Need::F32, true, false, false), Ok(true));
    assert_eq!(gate(Need::F64, true, true, false), Ok(true));
    // Missing hardware skips, unless the run requires it.
    assert_eq!(gate(Need::F32, false, false, false), Ok(false));
    assert_eq!(gate(Need::F64, false, false, true), Ok(false));
    let required = gate(Need::F32, false, true, false);
    assert!(required.is_err_and(|why| why.contains(REQUIRE_ENV)));
    let forbidden = gate(Need::F64, true, false, true);
    assert!(forbidden.is_err_and(|why| why.contains(EXPECT_NO_ENV)));
}

#[test]
fn test_sme2_support_backend_gate_decisions() {
    use Skip::{CappedBuild, CheckFailed, NoHardware, VerdictOpen};
    let passed = &Checked::Passed;
    // Hardware present, check passed, build not capped: run (whatever
    // REQUIRE says).
    assert_eq!(
        backend_gate(Need::F32, true, true, passed, false, false),
        Ok(None)
    );
    assert_eq!(
        backend_gate(Need::F64, true, true, passed, true, false),
        Ok(None)
    );
    // Hardware present, build capped: skip, or fail when REQUIRE is set,
    // with a message that names the cause; the verdict is not looked at.
    for checked in [passed, &Checked::Failed("x".to_owned()), &Checked::Open] {
        assert_eq!(
            backend_gate(Need::F32, true, false, checked, false, false),
            Ok(Some(CappedBuild))
        );
        let capped = backend_gate(Need::F64, true, false, checked, true, false);
        assert!(
            capped.as_ref().is_err_and(|why| why.contains(
                "this build caps SIMD below SME2 (force-scalar, max-simd-128 or max-simd-256)"
            ) && why.contains(REQUIRE_ENV)),
            "{capped:?}"
        );
    }
    // Hardware present, check failed: skip with the check's line, also when
    // REQUIRE is set (the kernel's own tests report the failure).
    let failed = Checked::Failed("the line".to_owned());
    for require in [false, true] {
        assert_eq!(
            backend_gate(Need::F64, true, true, &failed, require, false),
            Ok(Some(CheckFailed("the line".to_owned())))
        );
    }
    // Hardware present, verdict open (a thread that is not ready): skip, or
    // fail when REQUIRE is set.
    assert_eq!(
        backend_gate(Need::F32, true, true, &Checked::Open, false, false),
        Ok(Some(VerdictOpen))
    );
    let open = backend_gate(Need::F32, true, true, &Checked::Open, true, false);
    assert!(
        open.as_ref()
            .is_err_and(|why| why.contains("has not run") && why.contains(REQUIRE_ENV)),
        "{open:?}"
    );
    // Hardware missing: skip, capped or not, or fail when REQUIRE is set.
    for allowed in [true, false] {
        assert_eq!(
            backend_gate(Need::F32, false, allowed, passed, false, false),
            Ok(Some(NoHardware))
        );
        assert_eq!(
            backend_gate(Need::F64, false, allowed, passed, false, true),
            Ok(Some(NoHardware))
        );
        let required = backend_gate(Need::F32, false, allowed, passed, true, false);
        assert!(
            required.is_err_and(|why| why.contains(REQUIRE_ENV) && why.contains("not available"))
        );
        // Hardware present with EXPECT_NO set fails, capped or not, whatever
        // the verdict.
        for checked in [passed, &failed, &Checked::Open] {
            let forbidden = backend_gate(Need::F64, true, allowed, checked, false, true);
            assert!(forbidden.is_err_and(|why| why.contains(EXPECT_NO_ENV)));
        }
    }
    // The hardware gate is the backend gate with the caps and the verdict
    // ignored.
    for present in [true, false] {
        for require in [true, false] {
            for expect_no in [true, false] {
                assert_eq!(
                    gate(Need::F32, present, require, expect_no),
                    backend_gate(Need::F32, present, true, passed, require, expect_no)
                        .map(|skip| skip.is_none())
                );
            }
        }
    }
    // The backend is present only where the hardware is, and then exactly
    // when the first-use check passed and the build is not capped.
    for need in [Need::F32, Need::F64] {
        let backend = backend_present(need);
        assert!(!backend || hardware_present(need), "{need:?}");
        let passed = detect::verdict() == detect::Verdict::Passed;
        assert_eq!(
            backend,
            hardware_present(need) && SME2_ALLOWED && passed,
            "{need:?}"
        );
    }
}

